"""Broaden the curated Spellbook combo file from the bulk variants export (issues #1378, #1546).

The curated file ``data/meta/spellbook_combos.json`` held 7 hand-picked Chulane
lines (2026-10-25, text retrieval). This script rebuilds the machine-generated
part of the file from the Commander Spellbook bulk export
(``https://json.commanderspellbook.com/variants.json.gz`` or a local ``--bulk``
snapshot), under the operator's documented retrieval rules (no full export over
the paginated REST API):

* the bulk document is filtered locally — no collection or deck data leaves the
  machine;
* a variant is kept when its identity letters are a subset of WUG (colorless
  ``C`` counts as inside every identity), its status is ``OK``, it is legal in
  Commander, it is not a spoiler, no card is required to be a *different*
  commander (``mustBeCommander``), and every card it uses appears in the
  canonical Chulane corpus (``universe.resolve_universe`` for the commander,
  counted sections, quantity above zero — the ``combos.py`` name basis: full
  name or front face);
* variants whose card set equals a preserved (hand-curated) entry are skipped,
  and variants sharing one card set are merged into one entry.

Hand-curated entries are preserved verbatim and in order; entries generated by
this script carry the combo_id prefix ``chulane-sb-`` and are dropped and
regenerated on every run, so the script is idempotent. One measured deviation
of the old file against the strict corpus rule is reported, not repaired: the
preserved entry ``chulane-forager-turns`` uses Ethereal Forager, which appears
in the stored corpus only in a maybeboard section (never in a counted section
of a canonical deck).

Network access happens only with ``--allow-network``; without it and without ``--bulk`` the
script exits non-zero before it opens the store or a connection. The download is capped
(``--max-download-mb``, a declared ``Content-Length`` above the cap is refused before the body is
read) and the unpacked stream is read incrementally and capped (``--max-unpacked-mb``); neither
the compressed nor the unpacked document is held in memory (pattern of
``scripts/data_wave1/_common.py``).

On HTTP 403/429 (or any HTTP error) the script stops and reports the status —
no retries, no workarounds. The store must hold the repository data
(``import-all --from-repo``), as for ``scripts/subarchetype_analysis.py``.
"""

from __future__ import annotations

import argparse
import gzip
import json
import re
import sys
import tempfile
import urllib.error
import urllib.request
from collections.abc import Iterator
from pathlib import Path
from typing import IO, NamedTuple

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from commander_lab.studio.store import COUNTED_SECTIONS, StudioStore
from commander_lab.studio.universe import resolve_universe

GENERATED_PREFIX = "chulane-sb-"
DEFAULT_BULK_URL = "https://json.commanderspellbook.com/variants.json.gz"
DEFAULT_USER_AGENT = "mtg-combo-fetch-tool/1.0"
USER_AGENT = DEFAULT_USER_AGENT
WUG = frozenset("WUG")
_NETWORK_REFUSAL = (
    "No network access without --allow-network: pass --bulk <local variants.json[.gz]> to work "
    "offline, or --allow-network to download the bulk export once. Nothing was requested."
)

# Size limits, same defaults as scripts/data_wave1/_common.py (MiB, configurable per run).
MIB = 1 << 20
DEFAULT_MAX_DOWNLOAD_MB = 1024
DEFAULT_MAX_UNPACKED_MB = 4096
CHUNK_CHARS = 1 << 22
COMPACT_AFTER = 1 << 23
MAX_OBJECT_CHARS = 64 * MIB  # one variant object
_VARIANTS_KEY = re.compile(r'"variants"\s*:\s*\[')


class _Variant(NamedTuple):
    variant_id: str
    identity: str
    status: str
    spoiler: bool
    commander_legal: bool
    names: tuple[str, ...]
    foreign_commander: bool
    produces: tuple[str, ...]
    edhrec_decks: int | None


def _name_keys(name: str) -> set[str]:
    """The name keys a card answers to: its full name and its front face."""
    full = name.strip().casefold()
    keys = {full}
    if " // " in full:
        keys.add(full.split(" // ")[0].strip())
    return keys


def _corpus_keys(store: StudioStore, commander: str) -> tuple[set[str], int]:
    """Name keys of every card in the canonical corpus of ``commander``."""
    deck_ids = resolve_universe(store, {"commanders": [commander]})
    wanted = {str(deck_id) for deck_id in deck_ids}
    marks = ", ".join("?" for _ in COUNTED_SECTIONS)
    keys: set[str] = set()
    rows = store.connection.execute(
        f"SELECT deck_id, card_name FROM corpus_deck_card "
        f"WHERE section IN ({marks}) AND quantity > 0",
        COUNTED_SECTIONS,
    )
    for deck_id, card_name in rows:
        if str(deck_id) in wanted:
            keys.update(_name_keys(str(card_name)))
    return keys, len(deck_ids)


def _mib_limit(value: int, name: str) -> int:
    if value < 1:
        raise SystemExit(f"{name} must be at least 1 MiB")
    return value * MIB


def _download_bulk(
    url: str,
    dest: Path,
    *,
    user_agent: str = DEFAULT_USER_AGENT,
    max_bytes: int = DEFAULT_MAX_DOWNLOAD_MB * MIB,
) -> int:
    """One bulk GET streamed into ``dest``; returns the byte count.

    Any HTTP error stops the run with the status as evidence; a response that declares or
    delivers more than ``max_bytes`` is refused and nothing is kept.
    """
    if not url.startswith("https://"):
        raise SystemExit(f"Spellbook bulk download refused: not an https URL: {url}")
    request = urllib.request.Request(url, headers={"User-Agent": user_agent, "Accept": "*/*"})
    size = 0
    try:
        with urllib.request.urlopen(request, timeout=300) as response:
            declared = response.headers.get("Content-Length")
            if declared is not None and declared.isdigit() and int(declared) > max_bytes:
                raise SystemExit(
                    f"Spellbook bulk download refused: declared size {declared} exceeds "
                    f"the limit of {max_bytes} bytes"
                )
            with dest.open("wb") as sink:
                while True:
                    chunk = response.read(MIB)
                    if not chunk:
                        break
                    size += len(chunk)
                    if size > max_bytes:
                        raise SystemExit(
                            f"Spellbook bulk download refused: body exceeds the limit of "
                            f"{max_bytes} bytes"
                        )
                    sink.write(chunk)
    except urllib.error.HTTPError as error:
        detail = error.read().decode("utf-8", errors="replace")[:200]
        raise SystemExit(
            f"Spellbook bulk download stopped the run: HTTP {error.code} for {url} — {detail}"
        ) from error
    except urllib.error.URLError as error:
        raise SystemExit(
            f"Spellbook bulk download unreachable: {error.reason} for {url}"
        ) from error
    except SystemExit:
        dest.unlink(missing_ok=True)
        raise
    return size


def _iter_bulk_objects(handle: IO[str], max_unpacked: int) -> Iterator[object]:
    """The variant objects of a decoded bulk document, read incrementally.

    Accepts ``{"variants": [...]}`` or a bare list. Reads at most ``max_unpacked`` characters
    and never holds more than a window of the document (plus one object) in memory.
    """
    decoder = json.JSONDecoder()
    state = {"read": 0, "eof": False}

    def fill(buffer: str) -> str:
        if state["eof"]:
            return buffer
        chunk = handle.read(CHUNK_CHARS)
        if not chunk:
            state["eof"] = True
            return buffer
        state["read"] += len(chunk)
        if state["read"] > max_unpacked:
            raise SystemExit(
                f"Spellbook bulk export unpacks to more than {max_unpacked} characters"
            )
        return buffer + chunk

    buffer = fill("")
    pos = 0
    while True:
        stripped = buffer.lstrip()
        if stripped.startswith("["):
            pos = len(buffer) - len(stripped) + 1
            break
        found = _VARIANTS_KEY.search(buffer)
        if found:
            pos = found.end()
            break
        if state["eof"]:
            raise SystemExit("Spellbook bulk export lacks a 'variants' list")
        if len(buffer) > MAX_OBJECT_CHARS:
            raise SystemExit("Spellbook bulk export: no 'variants' list within the size limit")
        buffer = fill(buffer)
    while True:
        while True:
            while pos < len(buffer) and buffer[pos] in ", \n\r\t":
                pos += 1
            if pos < len(buffer):
                break
            if state["eof"]:
                raise SystemExit("Spellbook bulk export: the variants list is not closed")
            buffer = fill(buffer[pos:])
            pos = 0
        if buffer[pos] == "]":
            return
        try:
            item, end = decoder.raw_decode(buffer, pos)
        except json.JSONDecodeError:
            if state["eof"]:
                raise SystemExit("Spellbook bulk export: truncated or invalid JSON") from None
            if len(buffer) - pos > MAX_OBJECT_CHARS:
                raise SystemExit(
                    "Spellbook bulk export: one variant exceeds the size limit"
                ) from None
            buffer = fill(buffer[pos:])
            pos = 0
            continue
        pos = end
        yield item
        if pos > COMPACT_AFTER:
            buffer = buffer[pos:]
            pos = 0


def _open_bulk_text(path: Path) -> IO[str]:
    """Open a local bulk file as text, gunzipping on the fly when it is a gzip stream."""
    with path.open("rb") as probe:
        magic = probe.read(2)
    if magic == b"\x1f\x8b":
        return gzip.open(path, "rt", encoding="utf-8")
    return path.open("r", encoding="utf-8")


def _as_str(value: object) -> str:
    return value if isinstance(value, str) else ""


def _variant_facts(raw: object, commander: str) -> _Variant | None:
    """The fields this script uses from one bulk variant; None when malformed."""
    if not isinstance(raw, dict):
        return None
    names: list[str] = []
    foreign_commander = False
    raw_uses = raw.get("uses")
    if isinstance(raw_uses, list):
        for entry in raw_uses:
            if not isinstance(entry, dict):
                continue
            card = entry.get("card")
            name = _as_str(card.get("name")) if isinstance(card, dict) else ""
            if not name:
                return None
            names.append(name)
            if entry.get("mustBeCommander") is True and name != commander:
                foreign_commander = True
    produces: list[str] = []
    raw_produces = raw.get("produces")
    if isinstance(raw_produces, list):
        for item in raw_produces:
            if isinstance(item, dict):
                feature = item.get("feature")
                if isinstance(feature, dict):
                    feature_name = _as_str(feature.get("name"))
                    if feature_name and feature_name not in produces:
                        produces.append(feature_name)
    legalities = raw.get("legalities")
    commander_legal = legalities.get("commander") is True if isinstance(legalities, dict) else False
    popularity = raw.get("popularity")
    decks = popularity if isinstance(popularity, int) and not isinstance(popularity, bool) else None
    return _Variant(
        variant_id=_as_str(raw.get("id")),
        identity=_as_str(raw.get("identity")),
        status=_as_str(raw.get("status")),
        spoiler=raw.get("spoiler") is True,
        commander_legal=commander_legal,
        names=tuple(names),
        foreign_commander=foreign_commander,
        produces=tuple(produces),
        edhrec_decks=decks,
    )


def _load_bulk_variants(
    bulk_path: Path | None,
    *,
    bulk_url: str = DEFAULT_BULK_URL,
    commander: str,
    user_agent: str = DEFAULT_USER_AGENT,
    allow_network: bool = False,
    max_download_bytes: int = DEFAULT_MAX_DOWNLOAD_MB * MIB,
    max_unpacked_bytes: int = DEFAULT_MAX_UNPACKED_MB * MIB,
) -> list[_Variant]:
    """Load variants from a local ``variants.json[.gz]`` file or download the bulk export.

    A download needs ``allow_network``; without it (and without a local file) the run stops
    before any connection. Only the normalized per-variant facts are kept in memory.
    """
    if bulk_path is None and not allow_network:
        raise SystemExit(_NETWORK_REFUSAL)
    try:
        if bulk_path is not None:
            facts = _read_variant_facts(bulk_path, commander, max_unpacked_bytes)
        else:
            with tempfile.TemporaryDirectory(prefix="spellbook-bulk-") as folder:
                downloaded = Path(folder) / "variants.json.gz"
                _download_bulk(
                    bulk_url, downloaded, user_agent=user_agent, max_bytes=max_download_bytes
                )
                facts = _read_variant_facts(downloaded, commander, max_unpacked_bytes)
    except (UnicodeDecodeError, OSError, EOFError, json.JSONDecodeError) as error:
        raise SystemExit(f"Spellbook bulk export is not valid UTF-8 JSON: {error}") from error
    source_desc = str(bulk_path) if bulk_path is not None else bulk_url
    print(f"loaded {len(facts)} variants from bulk {source_desc}", file=sys.stderr)
    return facts


def _read_variant_facts(path: Path, commander: str, max_unpacked: int) -> list[_Variant]:
    facts: list[_Variant] = []
    with _open_bulk_text(path) as handle:
        for raw in _iter_bulk_objects(handle, max_unpacked):
            fact = _variant_facts(raw, commander)
            if fact is not None and fact.variant_id:
                facts.append(fact)
    return facts


def _entry_card_keys(combo: dict[str, object]) -> frozenset[str]:
    keys: set[str] = set()
    cards = combo.get("cards")
    if isinstance(cards, list):
        for name in cards:
            if isinstance(name, str):
                keys.update(_name_keys(name))
    return frozenset(keys)


def _preserved_violations(
    preserved: list[dict[str, object]], commander: str, corpus_keys: set[str]
) -> list[str]:
    """Preserved entries of ``commander`` whose cards leave the strict corpus rule."""
    violations: list[str] = []
    for combo in preserved:
        if str(combo.get("commander", "")) != commander:
            continue
        names: list[str] = []
        cards = combo.get("cards")
        if isinstance(cards, list):
            names.extend(name for name in cards if isinstance(name, str))
        any_of = combo.get("any_of")
        if isinstance(any_of, list):
            for group in any_of:
                if isinstance(group, list):
                    names.extend(name for name in group if isinstance(name, str))
        missing = [name for name in names if not (_name_keys(name) & corpus_keys)]
        if missing:
            violations.append(f"{combo.get('combo_id')}: {', '.join(missing)}")
    return violations


def _select_variants(
    facts: list[_Variant],
    *,
    corpus_keys: set[str],
    preserved_sets: set[frozenset[str]],
    commander: str,
    note: str,
) -> tuple[list[dict[str, object]], dict[str, int]]:
    """Filter the fetched variants into generated entries, with stage counts.

    A card set counts as seen only once a variant with that set is actually
    kept: a variant dropped for producing no feature never consumes its set,
    so a later variant with the same set and a result is still kept.
    """
    counts = {
        "fetched": len(facts),
        "identity_outside_wug": 0,
        "status_not_ok": 0,
        "not_commander_legal": 0,
        "spoiler": 0,
        "foreign_commander_required": 0,
        "card_outside_corpus": 0,
        "already_preserved": 0,
        "same_cardset_merged": 0,
        "no_produces": 0,
        "kept": 0,
        "kept_with_commander_card": 0,
        "kept_two_card": 0,
    }
    generated: list[dict[str, object]] = []
    seen_sets: set[frozenset[str]] = set()
    for fact in sorted(facts, key=lambda item: item.variant_id):
        identity_letters = set(fact.identity) - {"C"}
        if not identity_letters <= WUG:
            counts["identity_outside_wug"] += 1
            continue
        if fact.status != "OK":
            counts["status_not_ok"] += 1
            continue
        if not fact.commander_legal:
            counts["not_commander_legal"] += 1
            continue
        if fact.spoiler:
            counts["spoiler"] += 1
            continue
        if fact.foreign_commander:
            counts["foreign_commander_required"] += 1
            continue
        names = list(fact.names)
        if not names or any(not (_name_keys(name) & corpus_keys) for name in names):
            counts["card_outside_corpus"] += 1
            continue
        card_keys = frozenset(key for name in names for key in _name_keys(name))
        if card_keys in preserved_sets:
            counts["already_preserved"] += 1
            continue
        if card_keys in seen_sets:
            counts["same_cardset_merged"] += 1
            continue
        if not fact.produces:
            counts["no_produces"] += 1
            continue
        seen_sets.add(card_keys)
        ordered = sorted(set(names), key=str.casefold)
        if commander in ordered:
            ordered.remove(commander)
            ordered.insert(0, commander)
        generated.append(
            {
                "bands": ["high_power"],
                "cards": ordered,
                "combo_id": f"{GENERATED_PREFIX}{fact.variant_id}",
                "commander": commander,
                "edhrec_decks": fact.edhrec_decks,
                "notes": note,
                "result": ", ".join(fact.produces),
                "source": "commanderspellbook",
                "source_url": f"https://commanderspellbook.com/combo/{fact.variant_id}/",
                "tier": "A",
            }
        )
        counts["kept"] += 1
        if commander in names:
            counts["kept_with_commander_card"] += 1
        if len(set(names)) == 2:
            counts["kept_two_card"] += 1
    return generated, counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True, help="Studio data folder (store).")
    parser.add_argument(
        "--combos",
        default="data/meta/spellbook_combos.json",
        help="The curated combos file to extend (default: repo path).",
    )
    parser.add_argument(
        "--bulk",
        type=Path,
        default=None,
        help="Local variants.json or variants.json.gz bulk export (default: download --bulk-url).",
    )
    parser.add_argument("--bulk-url", default=DEFAULT_BULK_URL)
    parser.add_argument(
        "--allow-network",
        action="store_true",
        help="really download the bulk export (without it and without --bulk nothing is requested)",
    )
    parser.add_argument(
        "--max-download-mb",
        type=int,
        default=DEFAULT_MAX_DOWNLOAD_MB,
        help="refuse a download bigger than this many MiB",
    )
    parser.add_argument(
        "--max-unpacked-mb",
        type=int,
        default=DEFAULT_MAX_UNPACKED_MB,
        help="refuse a bulk document that unpacks to more than this many MiB of text",
    )
    parser.add_argument(
        "--user-agent",
        default=DEFAULT_USER_AGENT,
        help="Generic client User-Agent string (no project, repository, or person reference).",
    )
    parser.add_argument("--commander", default="Chulane, Teller of Tales")
    parser.add_argument(
        "--retrieved-at",
        required=True,
        help="Retrieval date (YYYY-MM-DD) recorded in notes and provenance.",
    )
    parser.add_argument("--dry-run", action="store_true", help="Count only, write nothing.")
    args = parser.parse_args()
    if args.bulk is None and not args.allow_network:
        raise SystemExit(_NETWORK_REFUSAL)
    max_download = _mib_limit(args.max_download_mb, "--max-download-mb")
    max_unpacked = _mib_limit(args.max_unpacked_mb, "--max-unpacked-mb")

    store = StudioStore.open(args.data)
    corpus_keys, deck_count = _corpus_keys(store, args.commander)
    print(f"canonical decks: {deck_count}; corpus name keys: {len(corpus_keys)}", file=sys.stderr)

    combos_path = Path(args.combos)
    data = json.loads(combos_path.read_text(encoding="utf-8"))
    raw_combos = data.get("combos")
    if not isinstance(raw_combos, list):
        raise SystemExit(f"{combos_path} carries no combos list")
    preserved: list[dict[str, object]] = []
    for combo in raw_combos:
        if isinstance(combo, dict) and not str(combo.get("combo_id", "")).startswith(
            GENERATED_PREFIX
        ):
            preserved.append(combo)
    preserved_sets = {_entry_card_keys(combo) for combo in preserved}
    violations = _preserved_violations(preserved, args.commander, corpus_keys)

    facts = _load_bulk_variants(
        args.bulk,
        bulk_url=args.bulk_url,
        commander=args.commander,
        user_agent=args.user_agent,
        allow_network=args.allow_network,
        max_download_bytes=max_download,
        max_unpacked_bytes=max_unpacked,
    )
    note = (
        f"Added {args.retrieved_at} from the Commander Spellbook bulk export "
        f"(issues #1378, #1546): color identity within WUG and every card appears in the "
        f"canonical Chulane corpus ({deck_count} decks, counted sections). "
        f"All-decks EDHREC count, NOT a Chulane count."
    )
    generated, counts = _select_variants(
        facts,
        corpus_keys=corpus_keys,
        preserved_sets=preserved_sets,
        commander=args.commander,
        note=note,
    )
    generated.sort(key=lambda combo: str(combo["combo_id"]))

    summary = {
        "commander": args.commander,
        "canonical_decks": deck_count,
        "corpus_name_keys": len(corpus_keys),
        "preserved_entries": len(preserved),
        "preserved_strict_rule_violations": violations,
        "counts": counts,
        "total_entries_after": len(preserved) + len(generated),
    }
    if not args.dry_run:
        provenance = data.get("provenance")
        if not isinstance(provenance, dict):
            provenance = {}
            data["provenance"] = provenance
        sources = provenance.get("sources")
        if not isinstance(sources, list):
            sources = []
            provenance["sources"] = sources
        bulk_source = (
            f"json.commanderspellbook.com bulk export (variants.json.gz, "
            f"retrieved {args.retrieved_at}, issues #1378/#1546)"
        )
        if bulk_source not in sources:
            sources.append(bulk_source)
        provenance["extension_1378"] = {
            "retrieved_at": args.retrieved_at,
            "endpoint": str(args.bulk) if args.bulk is not None else args.bulk_url,
            "retrieval_mode": "bulk",
            "scope": (
                "identity within WUG; status OK; Commander-legal; no spoiler; no card "
                "required as a different commander; every card in the canonical corpus "
                f"({deck_count} decks, counted sections)"
            ),
            "generated_entries": len(generated),
            "counts": counts,
        }
        data["combos"] = preserved + generated
        combos_path.write_text(
            json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False),
            encoding="utf-8",
        )
        summary["written"] = str(combos_path)
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
