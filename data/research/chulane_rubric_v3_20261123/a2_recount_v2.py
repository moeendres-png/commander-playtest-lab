#!/usr/bin/env python3
"""A2 recount on the generator v2 output (plan Bewertung v3, I1, test line under the G table).

Runs the UNCHANGED Phase-A2 script ``phaseA_scripts/A2/a2_inventory.py`` twice on a temporary
tree laid out like the repository: once with the v2 facts, patterns and card blocks ("before")
and once with facts_v2, patterns_v2 and the v2' blocks ("after"). The tree holds empty rating
files: no rating is read (the A2 keys that count rater verdicts or rater claims are 0 in both
runs and are not part of this recount).

Many A2 detectors fire on the condition itself (a hybrid symbol, an X cost, a planeswalker, a
creature back face, a named card, a fetch land whose fetched land enters tapped), not on the
defect, and two ruling checks read the shown-rulings constants of the renderer. For every A2 key
of the G table this module therefore adds a "resolved in the block" predicate and reports three
numbers per key: detector hits before, detector hits after, and cards still unresolved after,
counted over the union of the cards the detector flagged before or after.

  PYTHONPATH=src python3 data/research/chulane_rubric_v3_20261123/a2_recount_v2.py --repo .
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Callable, Mapping
from pathlib import Path
from typing import Any

Card = dict[str, Any]
Predicate = Callable[[Card, Card | None, str], bool]

V2_DIR = "data/research/chulane_rubric_v2_20261118"
V3_DIR = "data/research/chulane_rubric_v3_20261123"
A2_SCRIPT = f"{V3_DIR}/phaseA_scripts/A2/a2_inventory.py"
USER_FIRST_LINE = (
    "Rate this card. Answer with one JSON object that follows output_schema.json and nothing else."
)
SHIM = '''"""Shim for a2_inventory.py: serves precomputed card blocks (generated by a2_recount_v2)."""
import json
from pathlib import Path

_C = json.loads((Path(__file__).resolve().parent / "shim_config.json").read_text("utf-8"))
RULINGS_SHOWN = _C["rulings_shown"]
RULING_CHARS = _C["ruling_chars"]
USER_FIRST_LINE = _C["user_first_line"]


def card_block(f, pat):
    return _C["blocks"][f["oracle_id"]]


def user_prompt(f, pat):
    return USER_FIRST_LINE + "\\n\\n" + card_block(f, pat) + "\\n"
'''


def _glossary(repo: Path) -> dict[str, str]:
    data = json.loads((repo / V3_DIR / "mechanics_glossary.json").read_text("utf-8"))
    return {e["id"]: e["text"] for e in data["entries"]}


def _line(block: str, prefix: str) -> str:
    return next((ln for ln in block.splitlines() if ln.startswith(prefix)), "")


def predicates(repo: Path) -> dict[str, tuple[str, Predicate | None, str]]:
    """A2 key -> (correction, resolved(f, pat, block) or None = no fix, rule text)."""
    gl = _glossary(repo)

    def has(text: str) -> Predicate:
        return lambda f, p, b: text in b

    def gloss(term: str) -> Predicate:
        return lambda f, p, b: gl[term] in b

    def rulings_full(f: Card, p: Card | None, b: str) -> bool:
        return (
            all(
                f"  - {r['published_at']}: " + r["comment"].replace("\n", " ") in b
                for r in f["rulings"]
            )
            and "For more information on" not in b
        )

    def hybrid_ok(f: Card, p: Card | None, b: str) -> bool:
        cost = _line(b, "Mana cost:")
        mono = f.get("mono_pips_front") or {}
        return all(f"{s} x{n} (hybrid" in cost for s, n in f["hybrid_pips_front"].items()) and all(
            f"{c} x" not in cost.split("|")[-1].replace(f"/{c}", "").replace(f"{c}/", "")
            for c in "WUBRG"
            if not mono.get(c)
        )

    def no_etb_own_noncreature(f: Card, p: Card | None, b: str) -> bool:
        return not (p and "etb_own" in p["hits"] and not f["is_creature_front"])

    def no_role_label(f: Card, p: Card | None, b: str) -> bool:
        return not any(
            h and str(h[0]["line"]).startswith("roles by text")
            for h in (p or {"hits": {}})["hits"].values()
        )

    def back_pt(f: Card, p: Card | None, b: str) -> bool:
        return bool(re.search(r"^Face 2: .*\| Power/toughness: \d+/\d+:", b, re.M))

    def kw_labelled(f: Card, p: Card | None, b: str) -> bool:
        return "(face " in _line(b, "Power/toughness (front face):").split("| Keywords:")[1]

    def mana_labelled(f: Card, p: Card | None, b: str) -> bool:
        return "(face " in _line(b, "Power/toughness (front face):").split("| Produces mana:")[1]

    out: dict[str, tuple[str, Predicate | None, str]] = {
        "f_land_fetch_flag_wrong": ("G1", has("fetches a land: yes"), "'fetches a land: yes'"),
        "f_land_colours_none_but_fetches": (
            "G1",
            has("(fetchable: "),
            "fetchable deck colours shown (also 'none of the deck's colours')",
        ),
        "f_land_untapped_but_fetched_land_tapped": (
            "G1",
            has("fetched land enters: tapped"),
            "'fetched land enters: tapped'",
        ),
        "f_hybrid_pips_double_counted": ("G2", hybrid_ok, "hybrid counted apart, no doubled pips"),
        "f_castability_hybrid_phyrexian_left_out_not_said": (
            "G2",
            lambda f, p, b: (
                "hybrid symbols counted as their better option" in b
                and "(cost has no coloured symbol)" not in b
            ),
            "hybrid counted and labelled",
        ),
        "f_castability_x_at_zero_not_said": ("G3", has("(X counted as 0)"), "'(X counted as 0)'"),
        "f_castability_ignores_alt_cost_or_self_reduction": (
            "G3",
            has("cost reduction or alternative cost in the text not modelled"),
            "note 'not modelled'",
        ),
        "g_ruling_text_truncated_240": ("G4", rulings_full, "every ruling verbatim in the block"),
        "g_rulings_cut_more_than_4": ("G4", rulings_full, "every ruling verbatim in the block"),
        "g_rulings_same_date_arbitrary_selection": ("G4", rulings_full, "all rulings shown"),
        "g_ruling_empty_article_pointer": ("G4", rulings_full, "article pointer left out"),
        "g_prepare_definition_ruling_not_shown_in_full": (
            "G4",
            lambda f, p, b: gl["prepare"] in b,
            "prepare definition in the block (ruling or glossary line)",
        ),
        "f_pattern_etb_own_on_noncreature": ("G5", no_etb_own_noncreature, "no etb_own shown"),
        "f_pattern_evidence_is_role_label_not_text": (
            "G5",
            no_role_label,
            "no role-label evidence shown",
        ),
        "b_kw_unexplained::Goad": ("G6", gloss("goad"), "glossary line"),
        "b_kw_unexplained::Prepared": ("G6", gloss("prepare"), "glossary line"),
        "b_kw_unexplained::Cloak": ("G6", gloss("cloak"), "glossary line"),
        "b_scan_noreminder::prepared/prepare": ("G6", gloss("prepare"), "glossary line"),
        "b_scan_noreminder::cloak": ("G6", gloss("cloak"), "glossary line"),
        "b_scan_noreminder::loyalty ability": ("G6", gloss("loyalty_abilities"), "glossary line"),
        "b_scan_noreminder::ki counter (flip)": ("G6", None, "no repository source for flip"),
        "b_adventure_rule_unexplained": ("G6", gloss("adventure"), "glossary line"),
        "b_kw::Empower Jace": ("G6", gloss("empower"), "glossary line"),
        "b_scan::station": ("G6", gloss("station"), "glossary line (tiers: no source)"),
        "a_back_face_pt_missing": ("G7", back_pt, "face 2 power/toughness shown"),
        "a_keyword_from_other_face_unlabelled": ("G7", kw_labelled, "keyword with its face"),
        "a_produced_mana_from_other_face_unlabelled": ("G7", mana_labelled, "mana with its face"),
        "d_planeswalker_loyalty_missing": (
            "G8",
            lambda f, p, b: bool(re.search(r"^Loyalty: \d+", b, re.M)),
            "'Loyalty: N'",
        ),
        "c_named_reference_undefined": (
            "G9",
            has("Referenced card: "),
            "'Referenced card:' line (or 'none fixed' for a chosen name)",
        ),
        "c_token_no_reminder::Food": ("G10", gloss("token_food"), "glossary line"),
        "c_token_no_reminder::Treasure": ("G10", gloss("token_treasure"), "glossary line"),
        "c_token_no_reminder::Clue": ("G10", gloss("token_clue"), "glossary line"),
        "c_copy_effect": ("G10", None, "no repository source for the copy rule"),
        "f_body_benchmark_ignores_etb_counters": (
            "G11",
            has("[printed P/T; this card enters with counters"),
            "body benchmark note",
        ),
        "e_text_mentions_commander": (
            "G12",
            has("Commander (the deck's commander, for rule checks): Chulane, Teller of Tales"),
            "commander line",
        ),
    }
    return out


def _write_tree(
    repo: Path,
    root: Path,
    facts: list[Card],
    patterns: list[Card],
    blocks: Mapping[str, str],
    rulings_shown: int,
    ruling_chars: int,
) -> None:
    rub = root / V2_DIR
    for d in ("data", "scripts", "second_run_20261122", "second_run_full_20261122/rater"):
        (rub / d).mkdir(parents=True, exist_ok=True)
    (root / "data" / "cards").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(
        repo / "data/cards/xmage_card_facts.json", root / "data/cards/xmage_card_facts.json"
    )

    def jl(rows: list[Card]) -> str:
        return "".join(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n" for r in rows)

    (rub / "data/facts.jsonl").write_text(jl(facts), encoding="utf-8")
    (rub / "data/patterns.jsonl").write_text(jl(patterns), encoding="utf-8")
    (rub / "scripts/render_prompt.py").write_text(SHIM, encoding="utf-8")
    (rub / "scripts/shim_config.json").write_text(
        json.dumps(
            {
                "rulings_shown": rulings_shown,
                "ruling_chars": ruling_chars,
                "user_first_line": USER_FIRST_LINE,
                "blocks": dict(blocks),
            },
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )
    rows = [
        {
            "seq": i,
            "oracle_id": f["oracle_id"],
            "card": f["name"],
            "card_block": blocks[f["oracle_id"]],
        }
        for i, f in enumerate(facts, 1)
    ]
    (rub / "second_run_20261122/rr_input_1.jsonl").write_text(jl(rows), encoding="utf-8")
    (rub / "second_run_20261122/rr_output_1.jsonl").write_text("", encoding="utf-8")
    (rub / "fullrun_ratings.jsonl").write_text("", encoding="utf-8")
    src_rater = repo / V2_DIR / "second_run_full_20261122/rater"
    for g in sorted(src_rater.glob("rr2_guide_*.md")):
        shutil.copyfile(g, rub / "second_run_full_20261122/rater" / g.name)
    shutil.copyfile(
        repo / V2_DIR / "second_run_20261122/rr_guide_v2_1_rendered.md",
        rub / "second_run_20261122/rr_guide_v2_1_rendered.md",
    )


def run_a2(
    repo: Path,
    facts: list[Card],
    patterns: list[Card],
    blocks: Mapping[str, str],
    rulings_shown: int,
    ruling_chars: int,
) -> dict[str, Any]:
    """A2_metrics.json of the unchanged a2_inventory.py on a temporary tree."""
    with tempfile.TemporaryDirectory(prefix="a2_recount_") as tmp:
        root = Path(tmp) / "repo"
        out = Path(tmp) / "out"
        out.mkdir()
        _write_tree(repo, root, facts, patterns, blocks, rulings_shown, ruling_chars)
        env = dict(os.environ)
        env["PYTHONPATH"] = str(repo / "src")
        subprocess.run(
            [sys.executable, str(repo / A2_SCRIPT), "--repo", str(root), "--out", str(out)],
            check=True,
            env=env,
            stdout=subprocess.DEVNULL,
        )
        metrics: dict[str, Any] = json.loads((out / "A2_metrics.json").read_text("utf-8"))
        return metrics


def recount(
    repo: Path, facts: list[Card], patterns: list[Card], blocks: Mapping[str, str]
) -> dict[str, Any]:
    """Before/after detector counts and unresolved counts per A2 key of the G table."""
    v2_facts = [
        json.loads(x) for x in (repo / V2_DIR / "data/facts.jsonl").read_text("utf-8").splitlines()
    ]
    v2_pats = [
        json.loads(x)
        for x in (repo / V2_DIR / "data/patterns.jsonl").read_text("utf-8").splitlines()
    ]
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import render_prompt_v2 as rp

    ef = rp._load("extract_facts_v2")
    v2_ctx = rp.make_context(repo, ef.CORRECTIONS)
    vp = {p["oracle_id"]: p for p in v2_pats}
    v2_blocks = {f["oracle_id"]: rp.card_block(f, vp.get(f["oracle_id"]), v2_ctx) for f in v2_facts}
    before = run_a2(repo, v2_facts, v2_pats, v2_blocks, 4, 240)
    big = max(1, max(f["rulings_n"] for f in facts)) + 1
    after = run_a2(repo, facts, patterns, blocks, big, 10**9)
    fx = {f["oracle_id"]: f for f in facts}
    px = {p["oracle_id"]: p for p in patterns}
    preds = predicates(repo)
    rows: dict[str, Any] = {}
    for key, (g, pred, rule) in sorted(preds.items(), key=lambda kv: (int(kv[1][0][1:]), kv[0])):
        b_ids = before["defects"].get(key, {}).get("ids", [])
        a_ids = after["defects"].get(key, {}).get("ids", [])
        union = list(dict.fromkeys(b_ids + a_ids))
        open_ids = (
            union if pred is None else [o for o in union if not pred(fx[o], px.get(o), blocks[o])]
        )
        rows[key] = {
            "correction": g,
            "detector_before": len(b_ids),
            "detector_after": len(a_ids),
            "unresolved_after": len(open_ids),
            "unresolved_cards": sorted(fx[o]["name"] for o in open_ids),
            "resolved_when": rule,
        }
    target = ("G1", "G2", "G3", "G4", "G5", "G7", "G8", "G9")
    return {
        "script": A2_SCRIPT,
        "method": "a2_inventory.py unchanged on a temporary tree (empty rating files); "
        "unresolved = cards flagged before or after whose v2' block lacks the fix",
        "cards": after["n_cards"],
        "rerender_diff_after": after["h"]["rerender_diff"],
        "chulane_text_in_blocks": {
            "before": before["e"]["chulane_text_in_any_block"],
            "after": after["e"]["chulane_text_in_any_block"],
        },
        "keys": rows,
        "target_classes": list(target),
        "unresolved_in_target_classes": sum(
            r["unresolved_after"] for r in rows.values() if r["correction"] in target
        ),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=".")
    args = ap.parse_args(argv)
    repo = Path(args.repo).resolve()
    sys.path.insert(0, str(repo / "src"))
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import render_prompt_v2 as rp

    b = rp.build(repo)
    print(json.dumps(recount(repo, b.facts, b.patterns, b.blocks), indent=1, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
